import type { MapBounds } from '../gasStations';

/** Город чата: форма записи после валидации данных Directus. */
export interface ChatCity {
	/** Слаг в URL и в поле city сообщений чата. */
	slug: string;
	/** Название города в именительном падеже. */
	name: string;
	/** «в Тюмени», «в Екатеринбурге» — предложный падеж с предлогом. */
	inCity: string;
	/** «Тюмени», «Екатеринбурга» — родительный падеж. */
	ofCity: string;
	/** «по Тюмени», «по Екатеринбургу» — дательный падеж с предлогом. */
	byCity: string;
	/** «для Тюмени», «для Екатеринбурга» — родительный падеж с предлогом. */
	forCity: string;
	/** Короткая подпись для карточки города. */
	hint: string;
	/** Субъект РФ: «Тюменская область». */
	region: string;
	/** Население города, человек. */
	population: number;
	/** Показывать город первым в списках и меню. */
	isFeatured: boolean;
	/** Разрешено ли индексировать страницы города. */
	isIndexable: boolean;
	/** Переопределение title из Directus; пусто — используется шаблон. */
	seoTitle: string;
	/** Переопределение description из Directus; пусто — используется шаблон. */
	seoDescription: string;
	/** Границы города для карты АЗС: обязательны, иначе карта показывает не тот город. */
	bounds: MapBounds;
}
