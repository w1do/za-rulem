/** Федеральный округ по названию субъекта РФ. */
export const districtOfRegion = (region: string): string => districtByRegion[region] ?? '';

/** «861 тыс. жителей» — подпись размера города для интерфейса. */
export const formatPopulation = (population: number): string =>
	population >= 1_000_000
		? `${(population / 1_000_000).toFixed(1).replace('.', ',')} млн жителей`
		: `${Math.round(population / 1000)} тыс. жителей`;

/** Заголовок страницы города: приоритет у seo_title из Directus. */
export const citySeoTitle = (city: ChatCity): string =>
	city.seoTitle ||
	`Чат водителей ${city.ofCity}: цены на бензин и очереди на АЗС${city.region ? ` — ${city.region}` : ''}`;

/** Описание страницы города: приоритет у seo_description из Directus. */
export const citySeoDescription = (city: ChatCity): string => {
	if (city.seoDescription) return city.seoDescription;

	const district = districtOfRegion(city.region);
	const place = city.region ? ` (${city.region}${district ? `, ${district}` : ''})` : '';
	return `Живой чат водителей ${city.ofCity}${place}: где сейчас есть бензин и дизель, актуальные цены на топливо и очереди на АЗС ${city.ofCity} в реальном времени.`;
};
